/**
 * Builds client/public/rss.xml (English) and client/public/ar/rss.xml (Arabic)
 * from the article map in ArticleDetail.tsx, newest first.
 *
 *   node scripts/generate-rss.mjs
 *
 * Runs before `vite build` in vercel.json, so every deploy ships a feed that
 * includes the newest articles. The LinkedIn company page reads these feeds
 * (Page admin > Settings > Manage sources). Static files in client/public win
 * over the SPA rewrites, so the feeds are served as real XML.
 */
import fs from "node:fs";
import path from "node:path";

const ORIGIN = "https://foxsystemstech.com";
const SRC = path.join("client", "src", "pages", "ArticleDetail.tsx");
const STR = String.raw`"((?:[^"\\]|\\.)*)"`;

const xmlEsc = t =>
  t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const unJs = s => s.replace(/\\(["'\\])/g, "$1");

/** Returns [{ id, en: {title, subtitle, date, image}, ar: {...} }] */
export function readArticles(source) {
  const starts = [...source.matchAll(/^ {2}"([a-z0-9-]+)":\s*\{/gm)];
  if (starts.length === 0) throw new Error(`No article ids found in ${SRC}`);
  return starts.map((m, i) => {
    const chunk = source.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : undefined);
    const lang = key => {
      const at = chunk.search(new RegExp(`^ {4}${key}: \\{`, "m"));
      if (at < 0) return null;
      const rest = chunk.slice(at);
      const field = name => {
        const f = rest.match(new RegExp(`^ {6}${name}: ${STR}`, "m"));
        return f ? unJs(f[1]) : "";
      };
      return { title: field("title"), subtitle: field("subtitle"), date: field("date"), image: field("image") };
    };
    return { id: m[1], en: lang("en"), ar: lang("ar") };
  });
}

function feed(articles, lang) {
  const ar = lang === "ar";
  const base = ar ? `${ORIGIN}/ar` : ORIGIN;
  const items = articles
    .filter(a => a[lang] && a[lang].title && a[lang].date)
    .sort((a, b) => b[lang].date.localeCompare(a[lang].date) || a.id.localeCompare(b.id))
    .map(a => {
      const d = a[lang], link = `${base}/articles/${a.id}`;
      const pub = new Date(`${d.date}T08:00:00Z`).toUTCString();
      const img = d.image ? `\n      <enclosure url="${xmlEsc(d.image)}" type="image/jpeg" length="0" />` : "";
      return `    <item>
      <title>${xmlEsc(d.title)}</title>
      <link>${link}</link>
      <guid isPermaLink="true">${link}</guid>
      <pubDate>${pub}</pubDate>
      <description>${xmlEsc(d.subtitle || d.title)}</description>${img}
    </item>`;
    });
  const title = ar ? "فوكس سيستمز - المقالات" : "Fox Systems - Articles";
  const desc = ar
    ? "مقالات فوكس سيستمز عن أنظمة CRM والموارد البشرية والرواتب والمحاسبة وتقنية المعلومات في مصر والخليج."
    : "Fox Systems articles on CRM, HR and payroll, accounting and IT for businesses in Egypt and the Gulf.";
  const self = `${base}/rss.xml`;
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-rss.mjs; do not edit by hand. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${title}</title>
    <link>${base}/articles</link>
    <description>${desc}</description>
    <language>${ar ? "ar" : "en"}</language>
    <atom:link href="${self}" rel="self" type="application/rss+xml" />
${items.join("\n")}
  </channel>
</rss>
`;
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("generate-rss.mjs")) {
  const articles = readArticles(fs.readFileSync(SRC, "utf8"));
  const outEn = path.join("client", "public", "rss.xml");
  const outAr = path.join("client", "public", "ar", "rss.xml");
  fs.mkdirSync(path.dirname(outAr), { recursive: true });
  fs.writeFileSync(outEn, feed(articles, "en"));
  fs.writeFileSync(outAr, feed(articles, "ar"));
  const n = l => articles.filter(a => a[l]?.title && a[l]?.date).length;
  console.log(`RSS: ${n("en")} English items -> ${outEn}, ${n("ar")} Arabic items -> ${outAr}`);
}
