/**
 * Builds client/public/rss.xml (English) and client/public/ar/rss.xml (Arabic)
 * from the article map in ArticleDetail.tsx, newest first.
 *
 *   node scripts/generate-rss.mjs
 *
 * Runs before `vite build` in vercel.json, so every deploy ships a feed that
 * includes the newest articles. The LinkedIn company page reads these feeds
 * (Page admin > Settings > Manage sources). Static files in client/public win
 * over the SPA rewrites, so the feeds are served as real XML.
 */
import fs from "node:fs";
import path from "node:path";

const ORIGIN = "https://foxsystemstech.com";
const SRC = path.join("client", "src", "pages", "ArticleDetail.tsx");
const STR = String.raw`"((?:[^"\\]|\\.)*)"`;

const xmlEsc = t =>
  t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const unJs = s => s.replace(/\\(["'\\])/g, "$1");

/** Returns [{ id, en: {title, subtitle, date, image}, ar: {...} }] */
export function readArticles(source) {
  const starts = [...source.matchAll(/^ {2}"([a-z0-9-]+)":\s*\{/gm)];
  if (starts.length === 0) throw new Error(`No article ids found in ${SRC}`);
  return starts.map((m, i) => {
    const chunk = source.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : undefined);
    const lang = key => {
      const at = chunk.search(new RegExp(`^ {4}${key}: \\{`, "m"));
      if (at < 0) return null;
      const rest = chunk.slice(at);
      const field = name => {
        const f = rest.match(new RegExp(`^ {6}${name}: ${STR}`, "m"));
        return f ? unJs(f[1]) : "";
      };
      return { title: field("title"), subtitle: field("subtitle"), date: field("date"), image: field("image") };
    };
    return { id: m[1], en: lang("en"), ar: lang("ar") };
  });
}

/** One item per article per language in `langs`, newest first. */
function items(articles, langs) {
  return articles
    .flatMap(a => langs.filter(l => a[l] && a[l].title && a[l].date).map(l => {
      // Arabic at 08:00 UTC and English at 14:00 UTC, so the combined feed spreads the two posts over the day.
      const when = new Date(`${a[l].date}T${l === "ar" ? "08" : "14"}:00:00Z`);
      return { a, l, when };
    }))
    .sort((x, y) => y.when - x.when || x.a.id.localeCompare(y.a.id))
    .map(({ a, l, when }) => {
      const d = a[l], link = `${l === "ar" ? `${ORIGIN}/ar` : ORIGIN}/articles/${a.id}`;
      const img = d.image ? `\n      <enclosure url="${xmlEsc(d.image)}" type="image/jpeg" length="0" />` : "";
      return `    <item>
      <title>${xmlEsc(d.title)}</title>
      <link>${link}</link>
      <guid isPermaLink="true">${link}</guid>
      <pubDate>${when.toUTCString()}</pubDate>
      <description>${xmlEsc(d.subtitle || d.title)}</description>${img}
    </item>`;
    });
}

const CHANNELS = {
  en: { file: "rss.xml", langs: ["en"], language: "en", base: ORIGIN, title: "Fox Systems - Articles",
    desc: "Fox Systems articles on CRM, HR and payroll, accounting and IT for businesses in Egypt and the Gulf." },
  ar: { file: "ar/rss.xml", langs: ["ar"], language: "ar", base: `${ORIGIN}/ar`, title: "فوكس سيستمز - المقالات",
    desc: "مقالات فوكس سيستمز عن أنظمة CRM والموارد البشرية والرواتب والمحاسبة وتقنية المعلومات في مصر والخليج." },
  // Both languages in one feed: LinkedIn pages accept a single RSS source.
  all: { file: "rss-all.xml", langs: ["ar", "en"], language: "ar", base: ORIGIN, title: "Fox Systems - Articles / المقالات",
    desc: "Fox Systems articles in Arabic and English on CRM, HR and payroll, accounting and IT for Egypt and the Gulf." },
};

function feed(articles, key) {
  const c = CHANNELS[key];
  const list = items(articles, c.langs);
  return { count: list.length, xml: `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-rss.mjs; do not edit by hand. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${xmlEsc(c.title)}</title>
    <link>${c.base}/articles</link>
    <description>${xmlEsc(c.desc)}</description>
    <language>${c.language}</language>
    <atom:link href="${ORIGIN}/${c.file}" rel="self" type="application/rss+xml" />
${list.join("\n")}
  </channel>
</rss>
` };
}
if (process.argv[1]?.endsWith("generate-rss.mjs")) {
  const articles = readArticles(fs.readFileSync(SRC, "utf8"));
  for (const key of Object.keys(CHANNELS)) {
    const out = path.join("client", "public", ...CHANNELS[key].file.split("/"));
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const { count, xml } = feed(articles, key);
    fs.writeFileSync(out, xml);
    console.log(`RSS ${key}: ${count} items -> ${out}`);
  }
}
